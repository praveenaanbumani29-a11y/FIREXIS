"""Smoke propagation engine calculating optical density, visibility degradation, and toxic accumulation."""
import math
from typing import Dict, List, Any

class SmokeEngine:
    def __init__(self, width_m: float = 60.0, height_m: float = 40.0, cell_size_m: float = 2.0):
        self.width_m = width_m
        self.height_m = height_m
        self.cell_size_m = cell_size_m
        self.cols = int(width_m / cell_size_m)
        self.rows = int(height_m / cell_size_m)
        
        # Smoke density array [0.0 (clear) to 1.0 (blackout)]
        self.density: List[List[float]] = [[0.0 for _ in range(self.cols)] for _ in range(self.rows)]
        self.co_ppm: List[List[float]] = [[0.0 for _ in range(self.cols)] for _ in range(self.rows)]

    def step(self, fire_cells: List[Dict[str, Any]], dt_seconds: float = 1.0, diffusion_rate: float = 0.15):
        """Diffuses smoke generated by fire cells across the spatial matrix."""
        # 1. Source injection from active fire cells
        for fc in fire_cells:
            c = max(0, min(self.cols - 1, int(fc["x_m"] / self.cell_size_m)))
            r = max(0, min(self.rows - 1, int(fc["y_m"] / self.cell_size_m)))
            # Strong smoke generation from fire
            self.density[r][c] = min(1.0, self.density[r][c] + (0.25 * dt_seconds))
            self.co_ppm[r][c] = min(2000.0, self.co_ppm[r][c] + (150.0 * dt_seconds))

        # 2. Diffusion across neighboring cells (smoke moves rapidly in indoor corridors)
        new_density = [[self.density[r][c] for c in range(self.cols)] for r in range(self.rows)]
        
        for r in range(self.rows):
            for c in range(self.cols):
                curr = self.density[r][c]
                if curr > 0.01:
                    for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                        nr, nc = r + dr, c + dc
                        if 0 <= nr < self.rows and 0 <= nc < self.cols:
                            flow = (curr - self.density[nr][nc]) * diffusion_rate * dt_seconds
                            if flow > 0:
                                new_density[nr][nc] += flow * 0.25
                                new_density[r][c] -= flow * 0.25

        self.density = new_density

    def get_visibility_at(self, x_m: float, y_m: float) -> float:
        """Returns estimated visibility in meters (Jin's formula: Visibility = K / Od)."""
        c = max(0, min(self.cols - 1, int(x_m / self.cell_size_m)))
        r = max(0, min(self.rows - 1, int(y_m / self.cell_size_m)))
        d = max(0.001, self.density[r][c])
        # Unobscured visibility ~30m, dropping down to <1m in dense smoke
        return max(0.5, round(3.0 / (d * 5.0 + 0.1), 1))

    def get_hazard_metrics(self) -> Dict[str, Any]:
        """Returns summary metrics of smoke spread."""
        dense_cells = sum(1 for row in self.density for d in row if d > 0.4)
        total_cells = self.cols * self.rows
        pct_obscured = round((dense_cells / total_cells) * 100, 1)
        return {
            "percent_area_obscured": pct_obscured,
            "max_smoke_density": round(max(max(row) for row in self.density), 2)
        }
